import { readFileSync, writeFileSync, existsSync, mkdirSync, chmodSync, unlinkSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { adapterScriptPath, adaptersDir, ensureStateDir } from '../util/paths.js';
import { detectChatHandleInCwd } from '../util/mcp-config.js';
import type { Adapter, AdapterInstallOptions, AdapterResult } from './types.js';

const ADAPTER_NAME = 'claude-code-context';
const SCOPES = ['user', 'project', 'local'] as const;
type Scope = (typeof SCOPES)[number];

const MARKER_PREFIX = 'chat-mcp adapter';

interface CommandHookEntry {
  type?: string;
  command?: string;
  statusMessage?: string;
  [key: string]: unknown;
}

interface HookGroup {
  matcher?: string;
  hooks: CommandHookEntry[];
}

interface Settings {
  hooks?: Record<string, HookGroup[]>;
  [key: string]: unknown;
}

function markerFor(handle: string): string {
  return `${MARKER_PREFIX}: ${ADAPTER_NAME} (${handle})`;
}

function settingsPathForScope(scope: Scope, cwd: string): string {
  switch (scope) {
    case 'user':
      return join(homedir(), '.claude', 'settings.json');
    case 'project':
      return join(cwd, '.claude', 'settings.json');
    case 'local':
      return join(cwd, '.claude', 'settings.local.json');
  }
}

function scriptPath(handle: string): string {
  return adapterScriptPath(ADAPTER_NAME, handle);
}

function buildScript(handle: string, contextTotal: number): string {
  // Resolve the currently-running chat-mcp binary at install time so the hook
  // has a stable fallback if `chat-mcp` isn't on PATH (npx cache case). If the
  // cache rotates later, the user re-runs install to refresh these paths —
  // same DX as bumping the npx-pulled version.
  const nodeBin = process.execPath;
  const chatMcpEntry = process.argv[1] ?? '';

  return [
    '#!/usr/bin/env bash',
    `# ${markerFor(handle)}`,
    `# Auto-generated by: chat-mcp install ${ADAPTER_NAME} --handle ${handle} --context-total ${contextTotal}`,
    '# Do not hand-edit — re-run install to change.',
    '#',
    '# Fires on Claude Code PreToolUse. Reads the transcript_path from the hook',
    "# payload on stdin, estimates tokens from byte size (~3.5 chars/token), and",
    "# pushes a gauge report to chat-mcp so sibling peers + the human can see it.",
    '# Non-blocking: a broken bus never blocks a tool call.',
    '',
    `HANDLE=${JSON.stringify(handle)}`,
    `TOTAL=${JSON.stringify(String(contextTotal))}`,
    `CHATMCP_NODE=${JSON.stringify(nodeBin)}`,
    `CHATMCP_ENTRY=${JSON.stringify(chatMcpEntry)}`,
    '',
    'INPUT="$(cat)"',
    '',
    // Parse transcript_path out of the JSON payload. We shell out to node
    // (already available since chat-mcp is a node package) rather than depend
    // on jq being installed everywhere. If the payload is malformed we exit
    // quietly — a hook failure must not surface as a tool-call failure.
    'TRANSCRIPT="$("$CHATMCP_NODE" -e "',
    '  let s = \'\';',
    "  process.stdin.on('data', d => s += d);",
    "  process.stdin.on('end', () => {",
    '    try { const j = JSON.parse(s); process.stdout.write(j.transcript_path || \'\'); }',
    "    catch { process.stdout.write(''); }",
    '  });',
    '" <<< "$INPUT" 2>/dev/null)"',
    '',
    'if [ -z "$TRANSCRIPT" ] || [ ! -f "$TRANSCRIPT" ]; then',
    '  exit 0',
    'fi',
    '',
    "BYTES=\"$(wc -c < \"$TRANSCRIPT\" | tr -d ' ')\"",
    'USED="$(( BYTES * 10 / 35 ))"',
    '',
    // Guard against a jumbo transcript overshooting TOTAL — the CLI rejects
    // used > total. We clamp so the report still lands as "near-full."
    'if [ "$USED" -gt "$TOTAL" ]; then',
    '  USED="$TOTAL"',
    'fi',
    '',
    // Prefer `chat-mcp` on PATH (fast, global install); fall back to the
    // install-time-resolved node + entry pair (npx-cache case).
    'if command -v chat-mcp >/dev/null 2>&1; then',
    '  chat-mcp report-context --handle "$HANDLE" --used "$USED" --total "$TOTAL" >/dev/null 2>&1 &',
    'else',
    '  "$CHATMCP_NODE" "$CHATMCP_ENTRY" report-context --handle "$HANDLE" --used "$USED" --total "$TOTAL" >/dev/null 2>&1 &',
    'fi',
    '',
    'exit 0',
    '',
  ].join('\n');
}

function readSettings(path: string): Settings {
  if (!existsSync(path)) return {};
  const raw = readFileSync(path, 'utf8').trim();
  if (raw.length === 0) return {};
  const parsed = JSON.parse(raw) as unknown;
  if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
    throw new Error(`Expected an object in ${path}, got ${typeof parsed}`);
  }
  return parsed as Settings;
}

function writeSettings(path: string, settings: Settings): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, `${JSON.stringify(settings, null, 2)}\n`);
}

function isOurHookGroup(group: HookGroup, marker: string): boolean {
  return (group.hooks ?? []).some(
    (h) => typeof h.statusMessage === 'string' && h.statusMessage === marker,
  );
}

function upsertHook(settings: Settings, handle: string, script: string): boolean {
  const marker = markerFor(handle);
  const hooks = settings.hooks ?? {};
  const preToolUse: HookGroup[] = hooks.PreToolUse ?? [];

  const entry: HookGroup = {
    hooks: [
      {
        type: 'command',
        command: script,
        statusMessage: marker,
      },
    ],
  };

  const idx = preToolUse.findIndex((g) => isOurHookGroup(g, marker));
  if (idx >= 0) {
    if (JSON.stringify(preToolUse[idx]) === JSON.stringify(entry)) return false;
    preToolUse[idx] = entry;
  } else {
    preToolUse.push(entry);
  }

  hooks.PreToolUse = preToolUse;
  settings.hooks = hooks;
  return true;
}

function removeHook(settings: Settings, handle: string): boolean {
  const marker = markerFor(handle);
  if (!settings.hooks?.PreToolUse) return false;
  const before = settings.hooks.PreToolUse.length;
  const kept = settings.hooks.PreToolUse.filter((g) => !isOurHookGroup(g, marker));
  if (kept.length === before) return false;

  if (kept.length === 0) {
    delete settings.hooks.PreToolUse;
    if (Object.keys(settings.hooks).length === 0) {
      delete settings.hooks;
    }
  } else {
    settings.hooks.PreToolUse = kept;
  }
  return true;
}

function assertScope(scope: string | undefined): Scope {
  const s = (scope ?? 'local') as Scope;
  if (!SCOPES.includes(s)) {
    throw new Error(
      `Unknown scope "${scope}" for ${ADAPTER_NAME}. Valid: ${SCOPES.join(', ')} (default: local)`,
    );
  }
  return s;
}

function assertContextTotal(v: number | undefined): number {
  if (v == null || !Number.isFinite(v) || !Number.isInteger(v) || v <= 0) {
    throw new Error(
      `${ADAPTER_NAME} requires --context-total <n> (agent's model context-window size, e.g. 200000 for Sonnet, 1000000 for Opus 1M). Got: ${v}`,
    );
  }
  return v;
}

async function install(opts: AdapterInstallOptions): Promise<AdapterResult> {
  const scope = assertScope(opts.scope);
  const total = assertContextTotal(opts.contextTotal);
  const cwd = opts.cwd ?? process.cwd();

  // Same handle-mismatch guard as the wake adapter — if the tree's .mcp.json
  // launches chat-mcp with a different handle, a project/local-scope hook
  // will report under the wrong handle. --force opts out.
  if (!opts.force && (scope === 'local' || scope === 'project')) {
    const detected = detectChatHandleInCwd(cwd);
    if (detected && detected.handle !== opts.handle) {
      throw new Error(
        [
          `Handle mismatch: --handle "${opts.handle}" does not match the chat server handle in ${detected.sourcePath}.`,
          `  ${detected.sourcePath} launches the chat MCP with --handle "${detected.handle}".`,
          `  A "${scope}"-scope hook fires in this tree's Claude Code sessions, which register as "${detected.handle}", not "${opts.handle}".`,
          `  → to install for the tree's handle: re-run with --handle ${detected.handle}`,
          `  → to install anyway:                re-run with --force`,
        ].join('\n'),
      );
    }
  }

  const settingsPath = settingsPathForScope(scope, cwd);
  const script = scriptPath(opts.handle);

  ensureStateDir();
  mkdirSync(adaptersDir(), { recursive: true });
  writeFileSync(script, buildScript(opts.handle, total));
  chmodSync(script, 0o755);

  const settings = readSettings(settingsPath);
  const changed = upsertHook(settings, opts.handle, script);
  if (changed) writeSettings(settingsPath, settings);

  const summary = [
    `Installed chat-mcp Claude Code context-gauge adapter for handle "${opts.handle}".`,
    `  scope:    ${scope}`,
    `  total:    ${total} tokens`,
    `  hook:     ${script}`,
    `  settings: ${settingsPath}${changed ? '' : ' (already up to date)'}`,
    '',
    'Restart Claude Code (or open a new session) to pick up the PreToolUse hook.',
    'The hook fires on every tool call — the gauge stays null until the agent invokes',
    'a tool in the new session (any tool, including whoami), NOT on session start.',
    'Expect list_agents / whoami / the sidebar CTX column to populate on the next call.',
    scope === 'local' ? 'Note: .claude/settings.local.json is user-local; add it to .gitignore if it is not already.' : '',
  ].filter(Boolean).join('\n');

  return { changed: true, paths: [script, settingsPath], message: summary };
}

async function uninstall(opts: AdapterInstallOptions): Promise<AdapterResult> {
  const scope = assertScope(opts.scope);
  const cwd = opts.cwd ?? process.cwd();
  const settingsPath = settingsPathForScope(scope, cwd);
  const script = scriptPath(opts.handle);
  const paths: string[] = [];
  let changed = false;

  if (existsSync(settingsPath)) {
    const settings = readSettings(settingsPath);
    if (removeHook(settings, opts.handle)) {
      if (Object.keys(settings).length === 0) {
        unlinkSync(settingsPath);
      } else {
        writeSettings(settingsPath, settings);
      }
      paths.push(settingsPath);
      changed = true;
    }
  }

  if (existsSync(script)) {
    unlinkSync(script);
    paths.push(script);
    changed = true;
  }

  const summary = changed
    ? [
        `Removed chat-mcp Claude Code context-gauge adapter for handle "${opts.handle}".`,
        ...paths.map((p) => `  removed: ${p}`),
      ].join('\n')
    : `No chat-mcp Claude Code context-gauge adapter entries found for handle "${opts.handle}" at scope ${scope}.`;

  return { changed, paths, message: summary };
}

export const claudeCodeContextAdapter: Adapter = {
  name: ADAPTER_NAME,
  description: 'Claude Code — PreToolUse hook that reports context-window usage',
  scopes: SCOPES,
  defaultScope: 'local',
  install,
  uninstall,
};
